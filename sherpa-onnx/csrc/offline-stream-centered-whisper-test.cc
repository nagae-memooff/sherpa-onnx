std::vector<float> Wave(int n) {
  std::vector<float> x(n);
  for (int i = 0; i < n; ++i) x[i] = ((i * 37 % 257) - 128) / 128.0f;
  return x;
}
WhisperTag Centered() {
  WhisperTag tag;
  tag.dim = 128;
  tag.align_to_stft_center = true;
  return tag;
}
