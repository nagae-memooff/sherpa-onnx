TEST(CenteredWhisper, EmptySubFrameAndChunkedInput) {
  OfflineStream empty(Centered());
  EXPECT_TRUE(empty.GetFrames().empty());
  auto wave = Wave(4848);
  OfflineStream whole(Centered()), chunks(Centered());
  whole.AcceptWaveform(16000, wave.data(), wave.size());
  chunks.AcceptWaveform(16000, wave.data(), 64);
  EXPECT_TRUE(chunks.GetFrames().empty());
  chunks.AcceptWaveform(16000, wave.data()+64, wave.size()-64);
  EXPECT_EQ(whole.GetFrames(), chunks.GetFrames());
  EXPECT_EQ(chunks.GetFrames(), chunks.GetFrames());
}
